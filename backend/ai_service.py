import os
import json
import re
from typing import Dict, Any, List, Optional
import requests
from dotenv import load_dotenv

import schemas

load_dotenv()

OLLAMA_BASE_URL = os.getenv("OLLAMA_BASE_URL", "http://127.0.0.1:11434").rstrip('/')
OLLAMA_MODEL = os.getenv("OLLAMA_MODEL", "qwen2.5-coder:latest")
OLLAMA_TIMEOUT = int(os.getenv("OLLAMA_TIMEOUT_SECONDS", "90"))

class AIUnavailableError(Exception):
    """Raised when Ollama is unreachable, model missing, or API times out."""
    pass

class AIValidationError(Exception):
    """Raised when AI response is not valid JSON or fails schema validation."""
    pass

def check_ollama_status() -> Dict[str, Any]:
    """
    Check if local Ollama daemon is active and return available models.
    """
    try:
        resp = requests.get(f"{OLLAMA_BASE_URL}/api/tags", timeout=3)
        if resp.status_code == 200:
            data = resp.json()
            models = [m.get("name") for m in data.get("models", [])]
            return {
                "available": True,
                "base_url": OLLAMA_BASE_URL,
                "current_model": OLLAMA_MODEL,
                "installed_models": models,
                "model_ready": any(OLLAMA_MODEL.split(':')[0] in m for m in models)
            }
    except requests.exceptions.RequestException as e:
        return {
            "available": False,
            "base_url": OLLAMA_BASE_URL,
            "current_model": OLLAMA_MODEL,
            "installed_models": [],
            "model_ready": False,
            "error": f"Ollama is not running or unreachable at {OLLAMA_BASE_URL}. Ensure Ollama is installed and run 'ollama serve'."
        }
    return {
        "available": False,
        "base_url": OLLAMA_BASE_URL,
        "current_model": OLLAMA_MODEL,
        "installed_models": [],
        "model_ready": False,
        "error": "Unexpected response from Ollama API."
    }

def _query_ollama(prompt: str, system_prompt: str = "") -> str:
    """
    Sends a structured prompt to Ollama with strict timeout and error capture.
    """
    url = f"{OLLAMA_BASE_URL}/api/generate"
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": prompt,
        "system": system_prompt,
        "stream": False,
        "options": {
            "temperature": 0.2, # Lower temperature for stable JSON adherence
            "top_p": 0.9,
        },
        "format": "json" # Ollama's native JSON mode
    }

    try:
        response = requests.post(url, json=payload, timeout=OLLAMA_TIMEOUT)
    except requests.exceptions.ConnectError:
        raise AIUnavailableError(
            f"Could not connect to Ollama at {OLLAMA_BASE_URL}. Please start Ollama by running 'ollama serve' in your terminal."
        )
    except requests.exceptions.Timeout:
        raise AIUnavailableError(
            f"Ollama request timed out after {OLLAMA_TIMEOUT} seconds. The model may still be loading or system is under heavy load."
        )
    except requests.exceptions.RequestException as e:
        raise AIUnavailableError(f"Network error communicating with Ollama: {str(e)}")

    if response.status_code == 404:
        raise AIUnavailableError(
            f"Model '{OLLAMA_MODEL}' not found in Ollama. Pull it by running: 'ollama pull {OLLAMA_MODEL}' or 'ollama pull qwen2.5-coder'."
        )
    elif response.status_code != 200:
        raise AIUnavailableError(
            f"Ollama returned HTTP error {response.status_code}: {response.text}"
        )

    res_json = response.json()
    raw_response = res_json.get("response", "").strip()
    if not raw_response:
        raise AIUnavailableError("Ollama returned an empty response.")
    return raw_response

def _extract_and_parse_json(text: str) -> Dict[str, Any]:
    """
    Safely extract and parse JSON even if surrounded by markdown code blocks.
    """
    text = text.strip()
    # Strip markdown ```json ... ``` if present
    match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", text)
    if match:
        text = match.group(1).strip()
    
    try:
        return json.loads(text)
    except json.JSONDecodeError as err:
        # Try to locate first '{' and last '}'
        start = text.find('{')
        end = text.rfind('}')
        if start != -1 and end != -1 and end > start:
            try:
                return json.loads(text[start:end+1])
            except Exception:
                pass
        raise AIValidationError(f"Invalid JSON generated by AI model: {err}. Raw output was: {text[:200]}")


# ================= FEATURE 1: AI REQUIREMENT ANALYZER =================
def analyze_requirements(raw_input: str, project_name: str = "") -> schemas.RequirementAnalysisOutput:
    """
    Analyzes raw software project description and returns structured:
    - Problem Statement
    - Objectives
    - Target Users
    - Functional Requirements
    """
    system_prompt = (
        "You are an expert Agile Business Analyst and Software Architect. "
        "Analyze the provided software project description and output ONLY a valid JSON object matching the requested schema. "
        "Do not include any conversational filler."
    )

    prompt = f"""
Project Name: {project_name or 'Software Application'}
Raw Project Description:
\"\"\"{raw_input}\"\"\"

Extract and structure the requirements into this exact JSON schema:
{{
  "problem_statement": "A concise 2-4 sentence description of the core problem being solved.",
  "objectives": [
    "Specific business or user objective 1",
    "Specific business or user objective 2",
    "Specific business or user objective 3"
  ],
  "target_users": [
    "Target user persona 1 with their role",
    "Target user persona 2 with their role"
  ],
  "functional_requirements": [
    "The system shall ... (requirement 1)",
    "The system shall ... (requirement 2)",
    "The system shall ... (requirement 3)",
    "The system shall ... (requirement 4)",
    "The system shall ... (requirement 5)"
  ]
}}
"""
    raw_ai_text = _query_ollama(prompt, system_prompt)
    data = _extract_and_parse_json(raw_ai_text)

    try:
        validated = schemas.RequirementAnalysisOutput(**data)
        return validated
    except Exception as e:
        raise AIValidationError(f"Schema validation failed for requirement analysis: {str(e)}")


# ================= FEATURE 2 & 3: AI USER STORY & STORY MAP GENERATOR =================
def generate_user_story_map(project_name: str, requirement_summary: str) -> schemas.AIGeneratedStoryMap:
    """
    Generates full 2D User Story Map:
    Epics -> Activities -> Tasks -> User Stories with Acceptance Criteria and Story Points.
    """
    system_prompt = (
        "You are a Certified Scrum Product Owner and User Story Mapping Specialist. "
        "Deconstruct the software requirements into a hierarchical User Story Map: "
        "Epics -> User Activities -> User Tasks -> User Stories. "
        "Every user story MUST strictly use: As a [role], I want [action], So that [benefit]. "
        "Output ONLY a valid JSON object conforming to the requested schema."
    )

    prompt = f"""
Project: {project_name}
Requirements Summary:
\"\"\"{requirement_summary}\"\"\"

Generate 2 to 3 Epics.
Under each Epic, generate 1 to 2 User Activities.
Under each Activity, generate 1 to 2 User Tasks.
Under each Task, generate 1 to 2 User Stories with:
- title: Short descriptive title
- role: Persona role
- action: What the user wants to do
- benefit: Why they want it (value)
- acceptance_criteria: 2-3 specific testable criteria starting with 'Given... When... Then...' or clear conditions
- story_points: Fibonacci number (1, 2, 3, 5, 8)
- priority: One of 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'
- release_tag: 'MVP Release' or 'Release 2.0'

Output JSON schema:
{{
  "epics": [
    {{
      "epic_title": "Epic 1 Title",
      "description": "Brief description of the epic domain",
      "activities": [
        {{
          "activity_title": "User Activity Title (e.g. Account Onboarding)",
          "tasks": [
            {{
              "task_title": "User Task Title (e.g. Sign up with email)",
              "stories": [
                {{
                  "title": "Email Registration",
                  "role": "New Customer",
                  "action": "register using an email and password",
                  "benefit": "I can access my personal workspace securely",
                  "acceptance_criteria": [
                    "User provides valid email and password with at least 8 characters",
                    "Confirmation link is sent upon successful registration"
                  ],
                  "story_points": 3,
                  "priority": "HIGH",
                  "release_tag": "MVP Release"
                }}
              ]
            }}
          ]
        }}
      ]
    }}
  ]
}}
"""
    raw_ai_text = _query_ollama(prompt, system_prompt)
    data = _extract_and_parse_json(raw_ai_text)

    try:
        validated = schemas.AIGeneratedStoryMap(**data)
        return validated
    except Exception as e:
        raise AIValidationError(f"Schema validation failed for story map generation: {str(e)}")


